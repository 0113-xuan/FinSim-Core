async page => {
  const origin=new URL(page.url()).origin,errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(origin+'/vehicle.html');
  await page.getByRole('link',{name:'幫我選車',exact:true}).click();
  await page.locator('[name="budget_max"]').fill('2000000');
  await page.locator('[name="monthly_distance_km"]').fill('1000');
  await page.getByRole('checkbox',{name:'日常通勤',exact:true}).press('Space');
  await page.getByRole('button',{name:'下一步',exact:true}).press('Enter');
  await page.locator('[name="usual_passengers"]').fill('3');
  await page.locator('[name="ownership_years"]').selectOption('5');
  await page.locator('[name="parking_type"]').selectOption('own');
  await page.locator('[name="monthly_parking"]').fill('0');
  await page.locator('[name="payment_method"]').selectOption('financed');
  for(const [key,value] of Object.entries({down_payment:200000,annual_interest_rate:2.5,loan_term_months:84}))await page.locator(`[name="${key}"]`).fill(String(value));
  await page.locator('[name="include_financial"]').check();
  for(const [key,value] of Object.entries({salary:80000,balance:1200000,fixed_expense:12000,variable_expense:10000,required_monthly_debt:0}))await page.locator(`[name="${key}"]`).fill(String(value));
  await page.getByRole('button',{name:'下一步',exact:true}).click();
  await page.locator('[name="free_text"]').fill('我想保留原始需求，不要自行猜金額。');
  await page.getByRole('button',{name:'檢查需求',exact:true}).click();
  await page.locator('#reviewedNeeds').check();
  await page.getByRole('button',{name:'確認需求',exact:true}).click();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/decisions/vehicle/recommendations')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'查看符合條件車款',exact:true}).click();
  const response=await responsePromise,data=await response.json();
  await page.locator('#recommendationStatus').filter({hasText:'比較完成'}).waitFor();
  if(data.timezone!=='Asia/Taipei'||data.ranked.length!==6||data.incomplete.length!==1)throw new Error('Invalid recommendation response');
  const first=page.locator('.recommendation-card').first();
  await first.getByText('車款來源與限制',{exact:true}).click();
  if(!(await first.innerText()).includes('座位數 · 政府公開資料 · 僅索引佐證'))throw new Error('Altis seat evidence mislabeled');
  const honda=page.locator('.recommendation-card').filter({has:page.getByRole('heading',{name:'Honda FIT',exact:true})}).first();
  await honda.getByText('車款來源與限制',{exact:true}).click();
  if(!(await honda.innerText()).includes('座位數 · 品牌官方 · 已核對'))throw new Error('Honda seat source missing');
  const cc=page.locator('.recommendation-card').filter({has:page.getByRole('heading',{name:'Toyota Corolla Cross',exact:true})}).first();
  await cc.getByText('車款來源與限制',{exact:true}).click();
  if(!(await cc.innerText()).includes('座位數 · 第三方資料 · 僅索引佐證'))throw new Error('CC third-party source mislabeled');
  const text=await page.locator('#recommendationResults').innerText();
  if(!text.includes('五年後仍有 24 期')||!text.includes('通過系統財務限制'))throw new Error('Existing finance information missing');
  await page.getByText('資料不足，暫不排名（1）',{exact:true}).click();
  if(!(await page.locator('#recommendationResults').innerText()).includes('現行售價待確認'))throw new Error('Tesla uncertainty hidden');
  const geometry=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
  if(geometry.scrollWidth>geometry.width||errors.length)throw new Error('Layout or JS error '+errors.join(';'));
  await first.scrollIntoViewIfNeeded();
  await page.screenshot({path:'finsim-p2-final-desktop.png',fullPage:false});
  return {desktop:true,title:await page.title(),url:page.url(),geometry,errors,ranked:data.ranked.length,incomplete:data.incomplete.length,reference_date:data.reference_date,timeZone:data.timezone};
}
